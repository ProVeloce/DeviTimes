"""Flatten logo: fill white corner gaps with brand navy for sharp square icon."""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets" / "svt-logo-source.png"
NAVY = (26, 26, 46, 255)
OUT_PUBLIC = ROOT / "frontend" / "public" / "logo.png"
OUT_ELECTRON = ROOT / "electron" / "icon.png"
OUT_ELECTRON_LOGO = ROOT / "electron" / "logo.png"


def is_corner_gap(r: int, g: int, b: int, a: int) -> bool:
    if a < 16:
        return True
    # White / off-white padding from rounded-rect export
    if r > 235 and g > 235 and b > 235:
        return True
    return False


def process(src: Path) -> Image.Image:
    img = Image.open(src).convert("RGBA")
    w, h = img.size
    size = max(w, h)
    square = Image.new("RGBA", (size, size), NAVY)
    ox = (size - w) // 2
    oy = (size - h) // 2
    pixels = img.load()
    cleaned = Image.new("RGBA", (w, h), NAVY)
    for y in range(h):
        for x in range(w):
            r, g, b, a = pixels[x, y]
            if is_corner_gap(r, g, b, a):
                cleaned.putpixel((x, y), NAVY)
            else:
                cleaned.putpixel((x, y), (r, g, b, a))
    square.paste(cleaned, (ox, oy), cleaned)
    return square.resize((512, 512), Image.Resampling.LANCZOS)


def write_receipt_data_uri(img: Image.Image) -> None:
    import base64
    from io import BytesIO

    small = img.resize((128, 128), Image.Resampling.LANCZOS)
    buf = BytesIO()
    small.save(buf, format="PNG", optimize=True)
    b64 = base64.standard_b64encode(buf.getvalue()).decode("ascii")
    ts_path = ROOT / "frontend" / "src" / "lib" / "brand-logo-data.ts"
    ts_path.write_text(
        "// Auto-generated by scripts/process-logo.py — do not edit by hand\n"
        f"export const BRAND_LOGO_DATA_URI = 'data:image/png;base64,{b64}';\n",
        encoding="utf-8",
    )
    print(f"Wrote {ts_path}")


def main() -> None:
    out = process(SRC)
    OUT_PUBLIC.parent.mkdir(parents=True, exist_ok=True)
    OUT_ELECTRON.parent.mkdir(parents=True, exist_ok=True)
    out.save(OUT_PUBLIC, "PNG", optimize=True)
    out.save(OUT_ELECTRON, "PNG", optimize=True)
    out.save(OUT_ELECTRON_LOGO, "PNG", optimize=True)
    write_receipt_data_uri(out)
    print(f"Wrote {OUT_PUBLIC}")
    print(f"Wrote {OUT_ELECTRON}")
    print(f"Wrote {OUT_ELECTRON_LOGO}")


if __name__ == "__main__":
    main()
